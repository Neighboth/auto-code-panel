/** How complete is a locale, in percent of the reference (Turkish) key set. */
export function packCoverage(dictionary: Dictionary, reference: number): number {
  const translated = CORE_KEYS.filter((key) => Boolean(dictionary[key])).length;
  return Math.round((translated / reference) * 100);
}
