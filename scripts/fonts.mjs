#!/usr/bin/env node
/**
 * Generates the font catalogue (`src/lib/font-catalog.ts`).
 *
 * The store settings screen used to offer a hand-picked list of ~80 families.
 * The catalogue is now the complete Google Fonts library (≈1.6 k families with
 * their category and available subsets), generated from the
 * `google-fonts-complete` metadata package so it can be refreshed whenever
 * Google adds families:
 *
 *   npm i -D google-fonts-complete && node scripts/fonts.mjs
 *
 * The output is a compact tuple array, which keeps the file small enough to ship
 * to the browser (the picker filters it locally).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const ROOT = process.cwd();
const OUT = join(ROOT, "src", "lib", "font-catalog.ts");

const data = require("google-fonts-complete");
const CATEGORY = {
  "sans-serif": "Sans Serif",
  serif: "Serif",
  monospace: "Monospace",
  display: "Display",
  handwriting: "Handwriting",
};
/** Latin-ext first: these families render Turkish (ç, ğ, ı, İ, ş) correctly. */
const turkishSafe = (subsets) => Array.isArray(subsets) && (subsets.includes("latin-ext") || subsets.includes("latin"));

const families = Object.entries(data)
  .filter(([family, meta]) => family && typeof meta === "object" && meta.category)
  .map(([family, meta]) => ({
    family,
    category: CATEGORY[meta.category] ?? "Sans Serif",
    tr: turkishSafe(meta.subsets),
    variable: Boolean(meta.variants && Object.keys(meta.variants).length > 0),
  }))
  .sort((a, b) => a.family.localeCompare(b.family, "en"));

const rows = families
  .map((font) => `  [${JSON.stringify(font.family)}, ${JSON.stringify(font.category)}, ${font.tr ? 1 : 0}],`)
  .join("\n");

const previous = (() => {
  try {
    return JSON.parse(readFileSync(join(ROOT, "scripts", ".font-catalog.json"), "utf8"));
  } catch {
    return null;
  }
})();

const body = `/**
 * Complete Google Fonts catalogue — generated by \`scripts/fonts.mjs\`.
 *
 * Tuple layout: \`[family, category, hasTurkishGlyphs]\`. Do not edit by hand;
 * rerun the generator when Google publishes new families.
 *
 * ${families.length} families · ${families.filter((f) => f.tr).length} with Latin-ext (Turkish) coverage.
 */
export type FontCategory = "Sans Serif" | "Serif" | "Monospace" | "Display" | "Handwriting";

type FontRow = [string, FontCategory, 0 | 1];

const FONT_ROWS: FontRow[] = [
${rows}
];

export const FONT_CATALOG = FONT_ROWS.map(([family, category, tr]) => ({
  family,
  category,
  turkish: tr === 1,
}));

export type FontOption = { family: string; category: string };

/** Alphabetical list used by the picker (and by the server-side validation). */
export const FONT_OPTIONS: FontOption[] = FONT_CATALOG.map((font) => ({
  family: font.family,
  category: font.category,
}));

export const FONT_CATEGORIES: FontCategory[] = ["Sans Serif", "Serif", "Monospace", "Display", "Handwriting"];

export const FONT_COUNT = FONT_OPTIONS.length;
`;

writeFileSync(OUT, body);
writeFileSync(join(ROOT, "scripts", ".font-catalog.json"), JSON.stringify({ count: families.length }));
console.log(`${families.length} font yazıldı → ${OUT}` + (previous ? ` (önceki: ${previous.count})` : ""));
